// Deliberately small source assembler: no runtime loader or new dependencies.
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(import.meta.dirname, '..');
const sourceRoot = path.join(root, 'src');
const includes = /^[\t ]*(?:<!-- @include ([\w./-]+) -->|\/\* @include ([\w./-]+) \*\/|\/\/ @include ([\w./-]+))\r?$/gm;

export async function assemble(file, ancestors = []) {
  const resolved = path.resolve(sourceRoot, file);
  if (!resolved.startsWith(sourceRoot + path.sep)) throw new Error(`Include outside src: ${file}`);
  if (ancestors.includes(resolved)) throw new Error(`Circular include: ${file}`);
  const source = (await readFile(resolved, 'utf8')).replace(/\r\n/g, '\n');
  let output = '', offset = 0;
  for (const match of source.matchAll(includes)) {
    output += source.slice(offset, match.index);
    output += (await assemble(match[1] || match[2] || match[3], [...ancestors, resolved])).replace(/\n$/, '');
    offset = match.index + match[0].length;
  }
  return output + source.slice(offset);
}

export async function build({ check = false } = {}) {
  const targets = [
    ['index.html', 'index.html', '<!-- Generated by npm run build from src/index.html. Edit src/, not this file. -->\n'],
    ['trip/config.js', 'trip-config.js', '// Generated by npm run build from src/trip/config.js. Edit src/, not this file.\n']
  ];
  for (const [input, output, banner] of targets) {
    let generated = await assemble(input);
    generated = output.endsWith('.html') ? generated.replace('<!doctype html>\n', '<!doctype html>\n' + banner) : banner + generated;
    const filename = path.join(root, output);
    if (check) {
      const existing = (await readFile(filename, 'utf8')).replace(/\r\n/g, '\n');
      if (existing !== generated) throw new Error(`${output} is stale. Run npm run build and commit source + output.`);
    } else await writeFile(filename, generated);
  }
  console.log(check ? 'Generated app and trip config are current.' : 'Built index.html and trip-config.js.');
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  await build({ check: process.argv.includes('--check') });
}
